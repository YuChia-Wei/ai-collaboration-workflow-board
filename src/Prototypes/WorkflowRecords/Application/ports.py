"""Outbound persistence port used by workflow use cases.

Transaction handles are opaque to the application. Only the SQLite adapter
interprets them; command rules operate on ordinary workflow records.
"""
from typing import Any, ContextManager, Protocol

class WorkflowRepository(Protocol):
    def db(self) -> ContextManager[Any]: ...
    def begin_read(self, transaction: Any) -> None: ...
    def begin_write(self, transaction: Any) -> None: ...
    def load(self, transaction: Any, wid: str, ns: str) -> dict: ...
    def has_workflow(self, transaction: Any, wid: str) -> bool: ...
    def operation(self, transaction: Any, ns: str, oid: str) -> dict | None: ...
    def events(self, transaction: Any, ns: str, wid: str | None = None, after: int = 0) -> list: ...
    def workflows(self, transaction: Any, ns: str) -> list: ...
    def document_authored(self, transaction: Any, ns: str, wid: str, principal: str) -> bool: ...
    def put_blobs(self, transaction: Any, blobs: dict) -> None: ...
    def append_event(self, transaction: Any, event: dict) -> int: ...
    def save_workflow(self, transaction: Any, workflow: dict) -> None: ...
    def save_operation(self, transaction: Any, ns: str, oid: str, principal: str, payload_hash: str, result: dict) -> None: ...
    def export_payload(self, transaction: Any, ns: str) -> dict: ...
    def blob(self, transaction: Any, blob_hash: str) -> bytes | None: ...
    def all_blobs(self, transaction: Any) -> dict: ...
